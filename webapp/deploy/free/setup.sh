#!/usr/bin/env bash
# Studio on a fresh Ubuntu VM (made for Oracle Cloud Always Free, Ampere A1, Ubuntu 22.04 or 24.04; any Ubuntu
# box with a public IP works). Run from the repository checkout:
#
#   sudo webapp/deploy/free/setup.sh            # first time: installs Docker, opens 80/443, builds, starts
#   sudo webapp/deploy/free/setup.sh            # again later: pulls nothing, rebuilds and restarts what changed
#
# Safe to run again. Secrets are generated once into webapp/deploy/free/.env (never committed).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$HERE/.env"
COMPOSE=(docker compose -f "$HERE/docker-compose.yml" --env-file "$ENV_FILE")

[ "$(id -u)" = 0 ] || { echo "run with sudo"; exit 1; }
say() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

say "Docker"
if ! command -v docker >/dev/null; then
  apt-get update -q
  apt-get install -y -q ca-certificates curl git
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -q
  apt-get install -y -q docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi
docker --version

say "Firewall: ports 80 and 443"
# Oracle's Ubuntu images reject everything but SSH in iptables (the VCN security list must allow them too: README)
if command -v iptables >/dev/null; then
  for port in 80 443; do
    iptables -C INPUT -p tcp --dport "$port" -j ACCEPT 2>/dev/null || iptables -I INPUT 1 -p tcp --dport "$port" -j ACCEPT
  done
  if command -v netfilter-persistent >/dev/null; then netfilter-persistent save >/dev/null; fi
fi

say "User namespaces (Claude Code's sandbox)"
if sysctl -n kernel.apparmor_restrict_unprivileged_userns >/dev/null 2>&1; then
  echo "kernel.apparmor_restrict_unprivileged_userns=0" > /etc/sysctl.d/60-studio-userns.conf
  sysctl -q -w kernel.apparmor_restrict_unprivileged_userns=0
fi
echo "ok"

say "Swap (image builds need more than the free RAM on small VMs)"
if ! swapon --show | grep -q .; then
  fallocate -l 4G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi
swapon --show

say "Settings"
rand() { openssl rand -hex "${1:-24}"; }
if [ ! -f "$ENV_FILE" ]; then
  IP="$(curl -fsS https://api.ipify.org || curl -fsS https://ifconfig.me)"
  DASHED="${IP//./-}"
  GATE_PASSWORD="$(rand 9)"
  GATE_HASH="$(docker run --rm caddy:2.10-alpine caddy hash-password --plaintext "$GATE_PASSWORD")"
  # a Fernet key is 32 random bytes, URL-safe base64
  SECRETS_KEY="$(openssl rand -base64 32 | tr '+/' '-_')"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Studio on this VM. Generated by setup.sh on $(date -u +%F). Keep it private: it holds every secret of this install.
APP_HOST=${DASHED}.sslip.io
S3_HOST=s3.${DASHED}.sslip.io
# the shared password in front of the app (everyone on the team uses it, then signs in with their email)
GATE_USER=studio
GATE_PASSWORD=${GATE_PASSWORD}
GATE_HASH='${GATE_HASH}'
PG_PASSWORD=$(rand)
S3_USER=studio
S3_PASSWORD=$(rand)
SECRET_KEY=$(rand 32)
SECRETS_KEY=${SECRETS_KEY}
AUTH_MODE=dev
# comma list of emails that become admins on first sign-in
BOOTSTRAP_ADMINS=
# Claude tab: add a key from console.anthropic.com (set a monthly spend limit there), then rerun setup.sh
ANTHROPIC_API_KEY=
AGENT_BRAND_MONTHLY_BUDGET_USD=25
AGENT_TURN_BUDGET_USD=3
WHISPER_MODEL_DIR=/models
EOF
  echo "wrote $ENV_FILE"
fi
# shellcheck disable=SC1090
set -a; . "$ENV_FILE"; set +a

say "Build and start (the first build takes 20 to 40 minutes on a 2-core VM)"
"${COMPOSE[@]}" up -d --build --remove-orphans
"${COMPOSE[@]}" ps

say "Waiting for HTTPS"
for _ in $(seq 1 60); do
  if curl -fsS "https://${APP_HOST}/api/healthz" >/dev/null 2>&1; then break; fi
  sleep 5
done

cat <<EOF

  Studio:    https://${APP_HOST}
  Password:  user "${GATE_USER}", password "${GATE_PASSWORD}"   (the browser asks once)
  Then sign in with your email; the first person to sign in becomes admin.

  Logs:      ${COMPOSE[*]} logs -f api worker-agent
  Stop:      ${COMPOSE[*]} down          (data stays in Docker volumes)
EOF
if ! curl -fsS "https://${APP_HOST}/api/healthz" >/dev/null 2>&1; then
  echo
  echo "  HTTPS isn't answering yet. Check that ports 80 and 443 are open in the VM's security list (README.md),"
  echo "  then: ${COMPOSE[*]} logs caddy"
fi
